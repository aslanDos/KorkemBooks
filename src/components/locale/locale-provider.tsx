type LocaleContextValue = { locale: Locale; setLocale: (locale: Locale) => void };
const LocaleContext = createContext<LocaleContextValue>({ locale: "ru", setLocale: () => undefined });
const reverseKk = Object.fromEntries(Object.entries(kk).map(([ru, translation]) => [translation, ru]));

function translateValue(value: string, locale: Locale) {
  const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return value;
  const [, before, content, after] = match;
  const translated = locale === "kk" ? kk[content] : reverseKk[content];
  return translated ? `${before}${translated}${after}` : value;
}

function translateTree(root: ParentNode, locale: Locale) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    if (node.parentElement && !node.parentElement.closest("script, style, [data-no-translate]")) node.nodeValue = translateValue(node.nodeValue ?? "", locale);
    node = walker.nextNode();
  }
  if (root instanceof Element) translateElement(root, locale);
  root.querySelectorAll?.("[placeholder], [title], [aria-label]").forEach((element) => translateElement(element, locale));
}

function translateElement(element: Element, locale: Locale) {
  if (element.closest("[data-no-translate]")) return;
  for (const attribute of ["placeholder", "title", "aria-label"]) {
    const value = element.getAttribute(attribute);
    if (value) element.setAttribute(attribute, translateValue(value, locale));
  }
}

export function LocaleProvider({ initialLocale, children }: { initialLocale: Locale; children: ReactNode }) {
  const [locale, setLocaleState] = useState(initialLocale);
  const hydrationReadyRef = useRef(false);

  useEffect(() => {
    document.documentElement.lang = locale === "kk" ? "kk" : "ru";
    const pendingNodes = new Set<Node>();
    let animationFrame = 0;
    let settledFrame = 0;
    let translationTimer = 0;
    let hydrationDelayTimer = 0;
    let documentReady = hydrationReadyRef.current;

    const flushTranslations = () => {
      animationFrame = 0;
      for (const node of pendingNodes) {
        if (!node.isConnected) continue;
        if (node instanceof Text) node.nodeValue = translateValue(node.nodeValue ?? "", locale);
        else if (node instanceof Element) translateTree(node, locale);
      }
      pendingNodes.clear();
    };

    const scheduleTranslation = (node: Node) => {
      pendingNodes.add(node);
      if (!documentReady) return;
      if (animationFrame || settledFrame || translationTimer) return;
      // Next streams route segments into the document before React hydrates them.
      // Waiting for two paints and the following task keeps this DOM-only
      // translator from changing server text while hydration is in progress.
      animationFrame = window.requestAnimationFrame(() => {
        animationFrame = 0;
        settledFrame = window.requestAnimationFrame(() => {
          settledFrame = 0;
          translationTimer = window.setTimeout(() => {
            translationTimer = 0;
            flushTranslations();
          }, 350);
        });
      });
    };

    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) mutation.addedNodes.forEach(scheduleTranslation);
    });
    observer.observe(document.body, { childList: true, subtree: true });
    const translateInitialDocument = () => {
      hydrationReadyRef.current = true;
      documentReady = true;
      scheduleTranslation(document.body);
    };
    const scheduleInitialTranslation = () => {
      hydrationDelayTimer = window.setTimeout(translateInitialDocument, 1000);
    };
    if (documentReady) translateInitialDocument();
    else if (document.readyState === "complete") scheduleInitialTranslation();
    else window.addEventListener("load", scheduleInitialTranslation, { once: true });

    return () => {
      observer.disconnect();
      window.removeEventListener("load", scheduleInitialTranslation);
      if (animationFrame) window.cancelAnimationFrame(animationFrame);
      if (settledFrame) window.cancelAnimationFrame(settledFrame);
      if (translationTimer) window.clearTimeout(translationTimer);
      if (hydrationDelayTimer) window.clearTimeout(hydrationDelayTimer);
    };
  }, [locale]);

  const value = useMemo(() => ({ locale, setLocale: (nextLocale: Locale) => {
    document.cookie = `korkem-locale=${nextLocale}; path=/; max-age=31536000; samesite=lax`;
    setLocaleState(nextLocale);
  } }), [locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  return useContext(LocaleContext);
}

export function LanguageToggle() {
  const { setLocale } = useLocale();
  return <div className="language-toggle" data-no-translate><button className="locale-ru" type="button" onClick={() => setLocale("ru")}>RU</button><button className="locale-kk" type="button" onClick={() => setLocale("kk")}>KZ</button></div>;
}
