import { readFile, writeFile } from "node:fs/promises";

const sourcePath = "content/question-bank-ru-kk-v3.json";
const outputPath = "supabase/migrations/202609290001_update_ru_kk_question_bank.sql";
const bank = JSON.parse(await readFile(sourcePath, "utf8"));
const quote = (value) => `'${value.replaceAll("'", "''")}'`;

if (bank.version !== 3 || bank.types.length !== 11) throw new Error("Expected question bank v3 with 11 recipient types");
for (const type of bank.types) {
  const expectedChapters = ["girlfriend", "boyfriend"].includes(type.slug) ? 5 : 6;
  if (type.questionsPerChapter * expectedChapters !== 150) throw new Error(`Invalid chapter size: ${type.slug}`);
  for (const language of ["ru", "kk"]) {
    const locale = type.locales[language];
    if (locale.chapters.length !== expectedChapters) throw new Error(`Invalid chapters: ${language}/${type.slug}`);
    if (locale.questions.length !== 150 || new Set(locale.questions).size !== 150) throw new Error(`Invalid questions: ${language}/${type.slug}`);
    if (locale.questions.some((prompt) => !prompt.trim() || prompt.length > 1000)) throw new Error(`Invalid prompt: ${language}/${type.slug}`);
  }
}

const slugs = bank.types.map((type) => quote(type.slug)).join(", ");
const russianValues = bank.types.flatMap((type) => type.locales.ru.questions.map((prompt, index) =>
  `  (${quote(type.slug)}, ${index + 1}, ${quote(prompt)})`,
)).join(",\n");
const kazakhValues = bank.types.flatMap((type) => type.locales.kk.questions.map((prompt, index) =>
  `  (${quote(type.slug)}, ${index + 1}, ${quote(prompt)})`,
)).join(",\n");
const chapterLabelValues = bank.types.flatMap((type) => type.locales.ru.chapters.map((chapter, index) =>
  `  (${quote(type.slug)}, ${index + 1}, ${quote(chapter.title)}, ${quote(type.locales.kk.chapters[index].title)})`,
)).join(",\n");
const expandableSlugs = bank.types.filter((type) => type.slug !== "boyfriend").map((type) => quote(type.slug)).join(", ");

function chapterAssignments(indent = "  ") {
  const cases = bank.types.map((type) => {
    const ru = type.locales.ru.chapters.map((chapter) => quote(chapter.title)).join(", ");
    const kk = type.locales.kk.chapters.map((chapter) => quote(chapter.title)).join(", ");
    return `${indent}when ${quote(type.slug)} then\n${indent}  ru_titles := array[${ru}];\n${indent}  kk_titles := array[${kk}];`;
  }).join("\n");
  return `case book_type_slug\n${cases}\n${indent}else\n${indent}  ru_titles := array['С чего всё началось', 'Самое дорогое', 'Наши воспоминания', 'О главном и о будущем'];\n${indent}  kk_titles := array['Бәрі неден басталды', 'Ең қымбат нәрселер', 'Біздің естеліктеріміз', 'Ең маңыздысы және болашақ туралы'];\n${indent}end case;`;
}

const sql = `-- Generated by scripts/generate-question-bank-v3-migration.mjs.
-- Sources: user-provided Russian and Kazakh PDFs; wording preserved and whitespace normalized.
-- The approved Russian and Kazakh catalog contains 11 recipient types.

alter table public.question_catalog drop constraint if exists question_catalog_number_check;
alter table public.question_catalog
  add constraint question_catalog_number_check check (number between 1 and 150);

with source(slug, number, prompt) as (values
${russianValues}
)
insert into public.question_catalog(book_type_id, number, prompt)
select types.id, source.number, source.prompt
from source join public.book_types as types on types.slug = source.slug
on conflict (book_type_id, number) do update set prompt = excluded.prompt;

with source(slug, number, prompt) as (values
${kazakhValues}
)
insert into public.question_catalog_translations(catalog_id, language, prompt)
select catalog.id, 'kk'::public.book_language, source.prompt
from source
join public.book_types as types on types.slug = source.slug
join public.question_catalog as catalog on catalog.book_type_id = types.id and catalog.number = source.number
on conflict (catalog_id, language) do update set prompt = excluded.prompt;

-- Editable books receive the approved wording. Approved/production books remain frozen.
select set_config('app.changing_book_language', 'true', true);
update public.questions as questions
set prompt = coalesce(
  (select overrides.prompt from public.question_prompt_overrides as overrides
    where overrides.question_id = questions.id and overrides.language = books.language),
  (select translations.prompt from public.question_catalog_translations as translations
    where translations.catalog_id = catalog.id and translations.language = books.language),
  catalog.prompt
)
from public.question_catalog as catalog
join public.book_types as types on types.id = catalog.book_type_id and types.slug in (${slugs})
join public.books as books on books.type_id = types.id
where questions.catalog_id = catalog.id
  and questions.book_id = books.id
  and questions.deleted_at is null
  and books.deleted_at is null
  and books.production_status in ('writing', 'editing');

-- Keep the user's chapter layout intact: newly added questions enter the unassigned pool.
insert into public.questions(book_id, catalog_id, chapter_id, prompt, position)
select books.id, catalog.id, null, coalesce(translations.prompt, catalog.prompt), catalog.number
from public.books as books
join public.book_types as types on types.id = books.type_id and types.slug in (${slugs})
join public.question_catalog as catalog on catalog.book_type_id = types.id
left join public.question_catalog_translations as translations
  on translations.catalog_id = catalog.id and translations.language = books.language
where books.deleted_at is null and books.production_status in ('writing', 'editing')
on conflict (book_id, catalog_id) where catalog_id is not null do nothing;

-- Books that still have the untouched four-chapter layout can be expanded
-- without losing answers or user media. Customized structures stay untouched.
create temporary table question_bank_v3_standard_books as
select books.id as book_id, types.slug,
  case when types.slug = 'girlfriend' then 30 else 25 end as questions_per_chapter,
  case when types.slug = 'girlfriend' then 5 else 6 end as expected_chapter_count,
  books.language
from public.books as books
join public.book_types as types on types.id = books.type_id and types.slug in (${expandableSlugs})
where books.deleted_at is null
  and books.production_status in ('writing', 'editing')
  and (select count(*) from public.chapters where book_id = books.id and deleted_at is null) = 4
  and (select count(*)
    from public.questions as questions
    join public.question_catalog as catalog on catalog.id = questions.catalog_id and catalog.number <= 100
    where questions.book_id = books.id and questions.deleted_at is null and questions.chapter_id is not null) = 100
  and not exists (
    select 1
    from public.questions as questions
    join public.question_catalog as catalog on catalog.id = questions.catalog_id and catalog.number <= 100
    join public.chapters as chapters on chapters.id = questions.chapter_id and chapters.deleted_at is null
    where questions.book_id = books.id
      and questions.deleted_at is null
      and chapters.position <> (catalog.number - 1) / 25 + 1
  );

with labels(slug, position, ru, kk) as (values
${chapterLabelValues}
)
insert into public.chapters(book_id, title, position)
select eligible.book_id,
  case when eligible.language = 'kk' then labels.kk else labels.ru end,
  positions.position
from question_bank_v3_standard_books as eligible
join generate_series(5, 6) as positions(position) on positions.position <= eligible.expected_chapter_count
join labels on labels.slug = eligible.slug and labels.position = positions.position;

-- Replace only the former generated titles; custom chapter names are preserved.
with labels(slug, position, ru, kk) as (values
${chapterLabelValues}
), old_labels(position, ru, kk, en) as (values
  (1, 'С чего всё началось', 'Бәрі неден басталды', 'How It All Began'),
  (2, 'Самое дорогое', 'Ең қымбат нәрселер', 'What Matters Most'),
  (3, 'Наши воспоминания', 'Біздің естеліктеріміз', 'Our Memories'),
  (4, 'О главном и о будущем', 'Ең маңыздысы және болашақ туралы', 'What Matters and What Lies Ahead')
)
update public.chapters as chapters
set title = case when eligible.language = 'kk' then labels.kk else labels.ru end
from question_bank_v3_standard_books as eligible
join labels on labels.slug = eligible.slug
join old_labels on old_labels.position = labels.position
where chapters.book_id = eligible.book_id
  and chapters.position = labels.position
  and chapters.deleted_at is null
  and chapters.title in (old_labels.ru, old_labels.kk, old_labels.en);

update public.questions as questions
set chapter_id = chapters.id,
  position = (catalog.number - 1) % eligible.questions_per_chapter + 1
from public.question_catalog as catalog
join public.book_types as types on types.id = catalog.book_type_id
join question_bank_v3_standard_books as eligible on eligible.slug = types.slug
join public.chapters as chapters
  on chapters.book_id = eligible.book_id
 and chapters.position = (catalog.number - 1) / eligible.questions_per_chapter + 1
 and chapters.deleted_at is null
where questions.book_id = eligible.book_id
  and questions.catalog_id = catalog.id
  and questions.deleted_at is null;

drop table question_bank_v3_standard_books;

create or replace function public.instantiate_book_template(target_book_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare
  book_type uuid;
  book_type_slug text;
  selected_language public.book_language;
  expected_question_count integer;
  questions_per_chapter integer;
  expected_chapter_count integer;
  ru_titles text[];
  kk_titles text[];
  chapter_titles text[];
begin
  select books.type_id, types.slug, books.language
  into book_type, book_type_slug, selected_language
  from public.books as books
  join public.book_types as types on types.id = books.type_id
  where books.id = target_book_id and books.deleted_at is null
  for update of books;

  if not found or exists(select 1 from public.chapters where book_id = target_book_id) then return; end if;

  expected_question_count := case when book_type_slug in (${slugs}) then 150 else 100 end;
  questions_per_chapter := case when book_type_slug in ('girlfriend', 'boyfriend') then 30 else 25 end;
  expected_chapter_count := expected_question_count / questions_per_chapter;
  if (select count(*) from public.question_catalog where book_type_id = book_type) <> expected_question_count then
    raise exception 'Recipient catalog must contain % questions', expected_question_count;
  end if;

  ${chapterAssignments("  ")}
  chapter_titles := case when selected_language = 'kk' then kk_titles else ru_titles end;

  insert into public.chapters(book_id, title, position)
  select target_book_id, chapter_titles[position], position
  from generate_series(1, expected_chapter_count) as position;

  insert into public.questions(book_id, chapter_id, catalog_id, prompt, position)
  select target_book_id, chapters.id, catalog.id, coalesce(translations.prompt, catalog.prompt),
    (catalog.number - 1) % questions_per_chapter + 1
  from public.question_catalog as catalog
  join public.chapters as chapters
    on chapters.book_id = target_book_id
   and chapters.position = (catalog.number - 1) / questions_per_chapter + 1
  left join public.question_catalog_translations as translations
    on translations.catalog_id = catalog.id and translations.language = selected_language
  where catalog.book_type_id = book_type;
end;
$$;

create or replace function public.set_book_language(target_book_id uuid, target_language public.book_language)
returns boolean language plpgsql security definer set search_path = '' as $$
declare
  book_type_slug text;
  ru_titles text[];
  kk_titles text[];
  chapter_titles text[];
  system_titles text[];
begin
  select types.slug into book_type_slug
  from public.books as books
  join public.book_types as types on types.id = books.type_id
  where books.id = target_book_id and books.deleted_at is null
  for update of books;
  if not found then return false; end if;

  perform set_config('app.changing_book_language', 'true', true);
  update public.books set language = target_language where id = target_book_id;
  update public.questions as questions
  set prompt = coalesce(
    (select overrides.prompt from public.question_prompt_overrides as overrides
      where overrides.question_id = questions.id and overrides.language = target_language),
    (select translations.prompt from public.question_catalog_translations as translations
      where translations.catalog_id = questions.catalog_id and translations.language = target_language),
    (select catalog.prompt from public.question_catalog as catalog where catalog.id = questions.catalog_id)
  )
  where questions.book_id = target_book_id and questions.catalog_id is not null and questions.deleted_at is null;

  ${chapterAssignments("  ")}
  chapter_titles := case when target_language = 'kk' then kk_titles else ru_titles end;
  system_titles := ru_titles || kk_titles || array[
    'С чего всё началось', 'Самое дорогое', 'Наши воспоминания', 'О главном и о будущем',
    'Бәрі неден басталды', 'Ең қымбат нәрселер', 'Біздің естеліктеріміз', 'Ең маңыздысы және болашақ туралы',
    'How It All Began', 'What Matters Most', 'Our Memories', 'What Matters and What Lies Ahead'
  ];
  update public.chapters as chapters
  set title = chapter_titles[chapters.position]
  where chapters.book_id = target_book_id
    and chapters.deleted_at is null
    and chapters.position between 1 and coalesce(array_length(chapter_titles, 1), 0)
    and chapters.title = any(system_titles);
  return true;
end;
$$;

revoke all on function public.set_book_language(uuid, public.book_language) from public, anon, authenticated;
grant execute on function public.set_book_language(uuid, public.book_language) to service_role;
`;

await writeFile(outputPath, sql);
console.log(`Generated ${outputPath}: ${bank.types.length} types, ${bank.types.length * 150 * 2} localized questions`);
