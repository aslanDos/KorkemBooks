select catalog.id, 'kk'::public.book_language, source.prompt
from source
join public.book_types as types on types.slug = 'boyfriend'
join public.question_catalog as catalog on catalog.book_type_id = types.id and catalog.number = source.number
on conflict (catalog_id, language) do update set prompt = excluded.prompt;

-- Keep editable books aligned with the new wording without rewriting approved content.
select set_config('app.changing_book_language', 'true', true);
update public.questions as questions
set prompt = coalesce(translations.prompt, catalog.prompt)
from public.question_catalog as catalog
join public.book_types as types on types.id = catalog.book_type_id and types.slug = 'boyfriend'
join public.books as books on books.type_id = types.id
left join public.question_catalog_translations as translations
  on translations.catalog_id = catalog.id and translations.language = books.language
where questions.catalog_id = catalog.id
  and questions.book_id = books.id
  and questions.deleted_at is null
  and books.deleted_at is null
  and books.production_status in ('writing', 'editing');

-- New questions are added to the pool of existing editable books so their chapter layout is preserved.
insert into public.questions(book_id, catalog_id, chapter_id, prompt, position)
select books.id, catalog.id, null, coalesce(translations.prompt, catalog.prompt), catalog.number
from public.books as books
join public.book_types as types on types.id = books.type_id and types.slug = 'boyfriend'
join public.question_catalog as catalog on catalog.book_type_id = types.id and catalog.number > 100
left join public.question_catalog_translations as translations
  on translations.catalog_id = catalog.id and translations.language = books.language
where books.deleted_at is null and books.production_status in ('writing', 'editing')
on conflict (book_id, catalog_id) where catalog_id is not null do nothing;

create or replace function public.instantiate_book_template(target_book_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare
  book_type uuid;
  book_type_slug text;
  selected_language public.book_language;
  expected_question_count integer;
  questions_per_chapter integer;
  expected_chapter_count integer;
begin
  select books.type_id, types.slug, books.language
  into book_type, book_type_slug, selected_language
  from public.books as books
  join public.book_types as types on types.id = books.type_id
  where books.id = target_book_id and books.deleted_at is null
  for update of books;

  if not found or exists(select 1 from public.chapters where book_id = target_book_id) then return; end if;

  expected_question_count := case when book_type_slug = 'boyfriend' then 150 else 100 end;
  questions_per_chapter := case when book_type_slug = 'boyfriend' then 30 else 25 end;
  expected_chapter_count := case when book_type_slug = 'boyfriend' then 5 else 4 end;

  if (select count(*) from public.question_catalog where book_type_id = book_type) <> expected_question_count then
    raise exception 'Recipient catalog must contain % questions', expected_question_count;
  end if;

  insert into public.chapters(book_id, title, position)
  select target_book_id,
    case
      when book_type_slug = 'boyfriend' and selected_language = 'kk' then
        (array['Бәрі неден басталды', 'Мен сені осындайың үшін жақсы көремін', 'Тек екеуімізге түсінікті', 'Біз ұмытпайтын күндер', 'Сенімен бірге — алға'])[position]
      when book_type_slug = 'boyfriend' and selected_language = 'en' then
        (array['How It All Began', 'I Love You Just the Way You Are', 'Only We Understand', 'Days We Will Never Forget', 'Forward With You'])[position]
      when book_type_slug = 'boyfriend' then
        (array['С чего всё началось', 'Я люблю тебя таким', 'То, что понятно только нам', 'Дни, которые мы не забудем', 'С тобой — вперёд'])[position]
      when selected_language = 'kk' then
        (array['Бәрі неден басталды', 'Ең қымбат нәрселер', 'Біздің естеліктеріміз', 'Ең маңыздысы және болашақ туралы'])[position]
      when selected_language = 'en' then
        (array['How It All Began', 'What Matters Most', 'Our Memories', 'What Matters and What Lies Ahead'])[position]
      else
        (array['С чего всё началось', 'Самое дорогое', 'Наши воспоминания', 'О главном и о будущем'])[position]
    end,
    position
  from generate_series(1, expected_chapter_count) as position;

  insert into public.questions(book_id, chapter_id, catalog_id, prompt, position)
  select target_book_id, chapters.id, catalog.id, coalesce(translations.prompt, catalog.prompt),
    (catalog.number - 1) % questions_per_chapter + 1
  from public.question_catalog as catalog
  join public.chapters as chapters
    on chapters.book_id = target_book_id
   and chapters.position = (catalog.number - 1) / questions_per_chapter + 1
  left join public.question_catalog_translations as translations
    on translations.catalog_id = catalog.id
   and translations.language = selected_language
  where catalog.book_type_id = book_type;
end;
$$;

create or replace function public.set_book_language(target_book_id uuid, target_language public.book_language)
returns boolean language plpgsql security definer set search_path = '' as $$
declare
  book_type_slug text;
begin
  select types.slug into book_type_slug
  from public.books as books
  join public.book_types as types on types.id = books.type_id
  where books.id = target_book_id and books.deleted_at is null
  for update of books;

  if not found then return false; end if;

  perform set_config('app.changing_book_language', 'true', true);
  update public.books set language = target_language where id = target_book_id;

  update public.questions as questions
  set prompt = coalesce(
    (select overrides.prompt from public.question_prompt_overrides as overrides
      where overrides.question_id = questions.id and overrides.language = target_language),
    (select translations.prompt from public.question_catalog_translations as translations
      where translations.catalog_id = questions.catalog_id and translations.language = target_language),
    (select catalog.prompt from public.question_catalog as catalog where catalog.id = questions.catalog_id)
  )
  where questions.book_id = target_book_id
    and questions.catalog_id is not null
    and questions.deleted_at is null;

  with labels(position, ru, kk, en) as (
    select * from (values
      (1, 'С чего всё началось', 'Бәрі неден басталды', 'How It All Began'),
      (2, 'Я люблю тебя таким', 'Мен сені осындайың үшін жақсы көремін', 'I Love You Just the Way You Are'),
      (3, 'То, что понятно только нам', 'Тек екеуімізге түсінікті', 'Only We Understand'),
      (4, 'Дни, которые мы не забудем', 'Біз ұмытпайтын күндер', 'Days We Will Never Forget'),
      (5, 'С тобой — вперёд', 'Сенімен бірге — алға', 'Forward With You')
    ) as boyfriend_labels(position, ru, kk, en)
    where book_type_slug = 'boyfriend'
    union all
    select * from (values
      (1, 'С чего всё началось', 'Бәрі неден басталды', 'How It All Began'),
      (2, 'Самое дорогое', 'Ең қымбат нәрселер', 'What Matters Most'),
      (3, 'Наши воспоминания', 'Біздің естеліктеріміз', 'Our Memories'),
      (4, 'О главном и о будущем', 'Ең маңыздысы және болашақ туралы', 'What Matters and What Lies Ahead')
    ) as default_labels(position, ru, kk, en)
    where book_type_slug <> 'boyfriend'
  )
  update public.chapters as chapters
  set title = case target_language when 'kk' then labels.kk when 'en' then labels.en else labels.ru end
  from labels
  where chapters.book_id = target_book_id
    and chapters.position = labels.position
    and chapters.deleted_at is null
    and chapters.title in (labels.ru, labels.kk, labels.en);

  return true;
end;
$$;

revoke all on function public.set_book_language(uuid, public.book_language) from public, anon, authenticated;
grant execute on function public.set_book_language(uuid, public.book_language) to service_role;

create or replace function public.assign_book_questions(target_book_id uuid, question_ids uuid[], target_chapter_id uuid default null, only_unassigned boolean default false)
returns boolean language plpgsql security definer set search_path = '' as $$
declare
  next_position integer;
  question_count integer;
  allowed_count integer;
begin
  perform 1 from public.books where id = target_book_id and owner_id = auth.uid() and deleted_at is null for update;
  if not found then return false; end if;
  question_count := cardinality(question_ids);
  select count(*) into allowed_count from public.questions where book_id = target_book_id and deleted_at is null;
  if question_count is null or question_count < 1 or question_count > allowed_count then return false; end if;
  if target_chapter_id is not null and not exists (
    select 1 from public.chapters where id = target_chapter_id and book_id = target_book_id and deleted_at is null
  ) then return false; end if;
  if (select count(*) from public.questions where id = any(question_ids) and book_id = target_book_id
    and deleted_at is null and (not only_unassigned or chapter_id is null)) <> question_count then return false; end if;
  select coalesce(max(position), 0) into next_position from public.questions where chapter_id = target_chapter_id and deleted_at is null;
  update public.questions as questions set chapter_id = target_chapter_id, position = next_position + selected.ordinality::integer
  from unnest(question_ids) with ordinality as selected(id, ordinality) where questions.id = selected.id;
  update public.questions as questions set position = ordered.position
  from (select id, row_number() over (partition by chapter_id order by position, id)::integer as position
    from public.questions where book_id = target_book_id and chapter_id is not null and deleted_at is null) as ordered
  where questions.id = ordered.id and questions.position <> ordered.position;
  perform public.refresh_book_progress(target_book_id);
  return true;
end;
$$;

revoke all on function public.assign_book_questions(uuid, uuid[], uuid, boolean) from public, anon;
grant execute on function public.assign_book_questions(uuid, uuid[], uuid, boolean) to authenticated;
