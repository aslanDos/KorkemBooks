create or replace function public.instantiate_book_template(target_book_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare
  book_type uuid;
  selected_language public.book_language;
begin
  select type_id, language into book_type, selected_language
  from public.books
  where id = target_book_id and deleted_at is null
  for update;

  if not found or exists(select 1 from public.chapters where book_id = target_book_id) then return; end if;
  if (select count(*) from public.question_catalog where book_type_id = book_type) <> 100 then
    raise exception 'Recipient catalog must contain 100 questions';
  end if;

  insert into public.chapters(book_id, title, position)
  select target_book_id,
    case selected_language
      when 'kk' then (array['Бәрі неден басталды', 'Ең қымбат нәрселер', 'Біздің естеліктеріміз', 'Ең маңыздысы және болашақ туралы'])[position]
      when 'en' then (array['How It All Began', 'What Matters Most', 'Our Memories', 'What Matters and What Lies Ahead'])[position]
      else (array['С чего всё началось', 'Самое дорогое', 'Наши воспоминания', 'О главном и о будущем'])[position]
    end,
    position
  from generate_series(1, 4) as position;

  insert into public.questions(book_id, chapter_id, catalog_id, prompt, position)
  select target_book_id, chapters.id, catalog.id, coalesce(translations.prompt, catalog.prompt), (catalog.number - 1) % 25 + 1
  from public.question_catalog as catalog
  join public.chapters as chapters
    on chapters.book_id = target_book_id
   and chapters.position = (catalog.number - 1) / 25 + 1
  left join public.question_catalog_translations as translations
    on translations.catalog_id = catalog.id
   and translations.language = selected_language
  where catalog.book_type_id = book_type;
end;
$$;

create or replace function public.guard_book_question()
returns trigger language plpgsql set search_path = '' as $$
begin
  if tg_op = 'UPDATE' and (
    new.book_id is distinct from old.book_id
    or new.catalog_id is distinct from old.catalog_id
    or new.template_id is distinct from old.template_id
    or (new.prompt is distinct from old.prompt and coalesce(current_setting('app.changing_book_language', true), '') <> 'true')
  ) then
    raise exception 'Question identity and wording are immutable';
  end if;
  if new.catalog_id is not null and not exists (
    select 1 from public.question_catalog catalog
    join public.books books on books.type_id = catalog.book_type_id
    where catalog.id = new.catalog_id and books.id = new.book_id
  ) then raise exception 'Question does not belong to recipient catalog'; end if;
  if new.chapter_id is not null and not exists (
    select 1 from public.chapters where id = new.chapter_id and book_id = new.book_id and deleted_at is null
  ) then raise exception 'Invalid destination chapter'; end if;
  return new;
end;
$$;

create function public.guard_book_language_change()
returns trigger language plpgsql set search_path = '' as $$
begin
  if new.language is distinct from old.language
    and coalesce(current_setting('app.changing_book_language', true), '') <> 'true'
  then
    raise exception 'Book language can only be changed by an administrator';
  end if;
  return new;
end;
$$;

create trigger books_guard_language
before update of language on public.books
for each row execute function public.guard_book_language_change();

create function public.set_book_language(target_book_id uuid, target_language public.book_language)
returns boolean language plpgsql security definer set search_path = '' as $$
begin
  perform 1 from public.books where id = target_book_id and deleted_at is null for update;
  if not found then return false; end if;

  perform set_config('app.changing_book_language', 'true', true);
  update public.books set language = target_language where id = target_book_id;

  update public.questions as questions
  set prompt = coalesce(translations.prompt, catalog.prompt)
  from public.question_catalog as catalog
  left join public.question_catalog_translations as translations
    on translations.catalog_id = catalog.id
   and translations.language = target_language
  where questions.book_id = target_book_id
    and questions.catalog_id = catalog.id
    and questions.deleted_at is null;

  with labels(position, ru, kk, en) as (values
    (1, 'С чего всё началось', 'Бәрі неден басталды', 'How It All Began'),
    (2, 'Самое дорогое', 'Ең қымбат нәрселер', 'What Matters Most'),
    (3, 'Наши воспоминания', 'Біздің естеліктеріміз', 'Our Memories'),
    (4, 'О главном и о будущем', 'Ең маңыздысы және болашақ туралы', 'What Matters and What Lies Ahead')
  )
  update public.chapters as chapters
  set title = case target_language when 'kk' then labels.kk when 'en' then labels.en else labels.ru end
  from labels
  where chapters.book_id = target_book_id
    and chapters.position = labels.position
    and chapters.deleted_at is null
    and chapters.title in (labels.ru, labels.kk, labels.en);

  return true;
end;
$$;

revoke all on function public.set_book_language(uuid, public.book_language) from public, anon, authenticated;
